#!/usr/bin/env python3
"""Exact sum/sum-of-squares controls, independent of online recurrence.

Regenerate BeautyMomentOracles.h after changing the table below. Fraction
computes dyadic input exactly; Decimal supplies independently rounded SE.
"""
from fractions import Fraction as F
from decimal import Decimal, localcontext
from pathlib import Path

def oracle(n, k, x):
    x = F.from_float(x)
    count = n+k
    mean = (n+k*x)/count
    m2 = n+k*x*x-count*mean*mean
    high = float(mean)
    low = float(mean-F.from_float(high))
    with localcontext() as ctx:
        ctx.prec = 100
        se = (Decimal(m2.numerator)/Decimal(m2.denominator)/Decimal(count*(count-1))).sqrt()
    return [high,low,float(m2),float(se)]

cases = [(1,100000,1+2**-52),(1000000000,100000,1+2**-30),((1<<32)-1025,1024,1+2**-20)]
lines = ['// Generated by beauty_moment_oracles.py using exact rational sums.',
         'struct BeautyMomentOracle { unsigned int n,k; double x,mean,meanLow,m2,se; };',
         'static const BeautyMomentOracle beautyOracles[] = {']
for n,k,x in cases:
    vals = ', '.join(v.hex() for v in [x,*oracle(n,k,x)])
    lines.append(f'    {{{n}u,{k}u,{vals}}},')
lines.append('};\n')
Path(__file__).with_name('BeautyMomentOracles.h').write_text('\n'.join(lines))
