#!/usr/bin/env python3
"""Emit independent Fraction reference cases for exact stored-M2 resolution."""
import math
import random
import struct
from fractions import Fraction


def bits_to_double(bits):
    return struct.unpack('>d', struct.pack('>Q', bits))[0]


def cases():
    rng = random.Random(2026112645)
    counts = [2, 3, 5, 7, 17, 257, 1025, 10**9, (1 << 53)-1, 1 << 53]
    maximum = float.fromhex('0x1.fffffffffffffp+1023')
    minimum = float.fromhex('0x1p-1074')
    for n in counts:
        for high, low in [(maximum, -minimum), (1., minimum), (1., -minimum)]:
            yield n, high, low
    for i in range(100):
        biased = rng.choice([0, 1, 2, 53, 105, 512, 1023, 1536, 2045, 2046])
        high = bits_to_double((biased << 52) | rng.getrandbits(52))
        if high == 0:
            high = minimum
        quantum = biased - 1023 - 52 if biased else -1074
        low = math.ldexp(rng.random(), quantum - rng.choice([1, 2, 27, 53, 500, 2100]))
        if rng.randrange(2):
            low = -low
        exact = Fraction.from_float(high) + Fraction.from_float(low)
        if exact > Fraction.from_float(maximum):
            low = -abs(low)
        n = counts[i % len(counts)] if i % 2 else rng.randrange(2, (1 << 53)+1)
        yield n, high, low


if __name__ == '__main__':
    print('// Generated by radiometric_resolve_oracles.py; exact Fraction division.')
    print('const ResolveOracle resolveOracles[]={')
    for n, high, low in cases():
        exact = Fraction.from_float(high) + Fraction.from_float(low)
        high = float(exact)
        low = float(exact - Fraction.from_float(high))
        exact = Fraction.from_float(high) + Fraction.from_float(low)
        assert float(exact) == high
        sample = float(exact / (n - 1))
        mean = float(exact / (n * (n - 1)))
        print('    {%dULL,%s,%s,%s,%s,%s},' %
              (n, high.hex(), low.hex(), sample.hex(), mean.hex(), 'true' if mean else 'false'))
    print('};')
