//////////////////////////////////////////////////////////////////////
// HoleMaterial -- Lambertian BSDF; SPF either absent (mode 0) or the
// Lambertian SPF restricted to world x >= 0 (mode 1).
//////////////////////////////////////////////////////////////////////
class HoleMaterial : public IMaterial, public ISPF, public Reference
{
	LambertianMaterial* inner;
	int mode;

	static bool Open( const Vector3& w ) { return w.x >= 0; }

	void Filter( const ScatteredRayContainer& in, ScatteredRayContainer& out ) const
	{
		for( unsigned int i = 0; i < in.Count(); i++ ) {
			if( Open( in[i].ray.Dir() ) ) {
				out.AddScatteredRay( in[i] );
			}
		}
	}

protected:
	virtual ~HoleMaterial() { safe_release( inner ); }

public:
	HoleMaterial( LambertianMaterial* l, int m ) : inner( l ), mode( m ) { inner->addref(); }

	using IMaterial::Pdf;
	using IMaterial::PdfNM;

	IBSDF* GetBSDF() const override { return inner->GetBSDF(); }
	ISPF* GetSPF() const override { return mode == 0 ? nullptr : const_cast<HoleMaterial*>( this ); }
	IEmitter* GetEmitter() const override { return nullptr; }

	void Scatter( const RayIntersectionGeometric& ri, ISampler& sampler,
		ScatteredRayContainer& out, const IORStack& stack ) const override
	{
		ScatteredRayContainer all;
		inner->GetSPF()->Scatter( ri, sampler, all, stack );
		Filter( all, out );
	}
	void ScatterNM( const RayIntersectionGeometric& ri, ISampler& sampler, const Scalar nm,
		ScatteredRayContainer& out, const IORStack& stack ) const override
	{
		ScatteredRayContainer all;
		inner->GetSPF()->ScatterNM( ri, sampler, nm, all, stack );
		Filter( all, out );
	}
	Scalar Pdf( const RayIntersectionGeometric& ri, const Vector3& wo,
		const IORStack& stack ) const override
	{
		return Open( wo ) ? inner->GetSPF()->Pdf( ri, wo, stack ) : Scalar( 0 );
	}
	Scalar PdfNM( const RayIntersectionGeometric& ri, const Vector3& wo, const Scalar nm,
		const IORStack& stack ) const override
	{
		return Open( wo ) ? inner->GetSPF()->PdfNM( ri, wo, nm, stack ) : Scalar( 0 );
	}
};

class CapturingRasterizerOutput
	: public virtual IRasterizerOutput
	, public virtual Reference
{
public:
	std::vector<RISEColor> pixels;
	unsigned int width, height;
	CapturingRasterizerOutput() : width( 0 ), height( 0 ) {}
protected:
	virtual ~CapturingRasterizerOutput() {}
public:
	virtual void OutputIntermediateImage( const IRasterImage&, const Rect* ) override {}
	virtual void OutputImage( const IRasterImage& pImage, const Rect*, const unsigned int ) override
	{
		width = pImage.GetWidth();
		height = pImage.GetHeight();
		pixels.resize( width * height );
		for( unsigned int y = 0; y < height; y++ ) {
			for( unsigned int x = 0; x < width; x++ ) {
				pixels[y * width + x] = pImage.GetPEL( x, y );
			}
		}
	}
};

//! Mean composited luminance of the left / right image halves.
struct Halves { double left, right; };

static Halves HalfMeans( const CapturingRasterizerOutput& cap )
{
	Halves h = { -1.0, -1.0 };
	if( cap.pixels.empty() ) return h;
	double s[2] = { 0, 0 };
	unsigned n[2] = { 0, 0 };
	for( unsigned y = 0; y < cap.height; y++ ) {
		for( unsigned x = 0; x < cap.width; x++ ) {
			const RISEColor& c = cap.pixels[y * cap.width + x];
			const double l = c.a * ( 0.2126 * c.base.r + 0.7152 * c.base.g + 0.0722 * c.base.b );
			if( !std::isfinite( l ) ) return h;
			const int k = ( 2 * x < cap.width ) ? 0 : 1;
			s[k] += l;
			n[k]++;
		}
	}
	h.left = s[0] / n[0];
	h.right = s[1] / n[1];
	return h;
}

static std::string WriteSceneToTempFile( const std::string& sceneText, const char* tag )
{
	char path[512];
	const char* tmpBase = std::getenv( "TMPDIR" );
	if( !tmpBase || !*tmpBase ) tmpBase = "/tmp";
	std::snprintf( path, sizeof(path), "%s/bdpt_zero_density_%s_%d.RISEscene",
		tmpBase, tag, static_cast<int>( ::getpid() ) );
	std::ofstream ofs( path );
	if( !ofs.is_open() ) return std::string();
	ofs << sceneText;
	return std::string( path );
}

//! Renders once; `holeMode` < 0 keeps the scene's Lambertian floor.
static Halves RenderHalves( const char* scenePath, int holeMode, unsigned salt )
{
	Halves bad = { -1.0, -1.0 };
	IJobPriv* pJob = nullptr;
	if( !RISE_CreateJobPriv( &pJob ) || !pJob ) return bad;
	if( !pJob->LoadAsciiSceneViaCst( scenePath ) ) {
		safe_release( pJob );
		return bad;
	}
	if( holeMode >= 0 ) {
		IObjectPriv* pFloor = pJob->GetObjects()->GetItem( "obj_quad" );
		if( !pFloor ) { safe_release( pJob ); return bad; }
		UniformColorPainter* pPaint = new UniformColorPainter( RISEPel( 0.5, 0.5, 0.5 ) );
		LambertianMaterial* pLamb = new LambertianMaterial( *pPaint );
		HoleMaterial* pHole = new HoleMaterial( pLamb, holeMode );
		pFloor->AssignMaterial( *pHole );
		safe_release( pHole );
		safe_release( pLamb );
		safe_release( pPaint );
	}
	pJob->RemoveRasterizerOutputs();
	CapturingRasterizerOutput* pCap = new CapturingRasterizerOutput();
	GlobalLog()->PrintNew( pCap, __FILE__, __LINE__, "test capture output" );
	pJob->GetRasterizer()->AddRasterizerOutput( pCap );
	std::srand( 430000u + salt );
	SobolSamplerTestHooks::ValueSalt().store( SobolSequence::HashCombine( 0x430u, salt ) );
	const bool bRendered = pJob->Rasterize();
	SobolSamplerTestHooks::ValueSalt().store( 0u );
	const Halves h = bRendered ? HalfMeans( *pCap ) : bad;
	safe_release( pCap );
	safe_release( pJob );
	return h;
}

struct Stat { double mean[2], sd[2]; bool ok; };

static Stat SaltedHalves( const std::string& scene, const char* tag, int holeMode, int n )
{
	Stat s = { { 0, 0 }, { 0, 0 }, false };
	const std::string path = WriteSceneToTempFile( scene, tag );
	if( path.empty() ) return s;
	double sum[2] = { 0, 0 }, sumSq[2] = { 0, 0 };
	for( int i = 0; i < n; i++ ) {
		const Halves h = RenderHalves( path.c_str(), holeMode, unsigned( i ) + 1u );
		if( h.left < 0 ) { std::remove( path.c_str() ); return s; }
		const double v[2] = { h.left, h.right };
		for( int k = 0; k < 2; k++ ) { sum[k] += v[k]; sumSq[k] += v[k] * v[k]; }
	}
	std::remove( path.c_str() );
	for( int k = 0; k < 2; k++ ) {
		s.mean[k] = sum[k] / n;
		s.sd[k] = n > 1 ? std::sqrt( std::max( 0.0, ( sumSq[k] - n * s.mean[k] * s.mean[k] ) / ( n - 1 ) ) ) : 0.0;
	}
	s.ok = true;
	return s;
}

