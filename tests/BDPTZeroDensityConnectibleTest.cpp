static const int kRepeats = 4;
// Mean band against the PT Lambertian reference, per image half.  The
// measured salted sd of a half-mean is ~0.1-0.3 % at this sample count
// (printed below); the defect it guards against is a factor of ~0.006
// (null SPF) and ~0.5 on the hole half (half SPF).
static const double kBand = 0.03;

static void Compare( const char* label, const Stat& got, const Stat& ref )
{
	for( int k = 0; k < 2; k++ ) {
		const double ratio = ref.mean[k] > 0 ? got.mean[k] / ref.mean[k] : -1.0;
		std::printf( "  %-26s %s half: %.6f (sd %.6f)   ref %.6f   ratio %.5f\n",
			label, k == 0 ? "left " : "right", got.mean[k], got.sd[k], ref.mean[k], ratio );
		Check( got.ok && std::fabs( ratio - 1.0 ) <= kBand,
			std::string( label ) + ( k == 0 ? " left" : " right" ) + " half within band of PT Lambertian" );
	}
}

int main()
{
	std::cout << "DL-430: zero sampling density at a non-delta connectible vertex" << std::endl;
	const Stat ref = SaltedHalves( Scene( kPT ), "pt_lamb", -1, kRepeats );
	Check( ref.ok && ref.mean[0] > 0 && ref.mean[1] > 0, "PT Lambertian reference renders" );
	std::printf( "  PT lambertian (reference)  left %.6f (sd %.6f)   right %.6f (sd %.6f)\n",
		ref.mean[0], ref.sd[0], ref.mean[1], ref.sd[1] );

	struct Row { const char* label; const char* rast; const char* tag; int mode; };
	const Row rows[] = {
		{ "PT null SPF",       kPT,   "pt_null",    0 },
		{ "PT half SPF",       kPT,   "pt_half",    1 },
		{ "BDPT lambertian",   kBDPT, "bdpt_lamb", -1 },
		{ "BDPT null SPF",     kBDPT, "bdpt_null",  0 },
		{ "BDPT half SPF",     kBDPT, "bdpt_half",  1 },
		{ "VCM null SPF",      kVCM,  "vcm_null",   0 },
		{ "VCM half SPF",      kVCM,  "vcm_half",   1 },
	};
	for( const Row& r : rows ) {
		Compare( r.label, SaltedHalves( Scene( r.rast ), r.tag, r.mode, kRepeats ), ref );
	}

	std::cout << std::endl << "BDPTZeroDensityConnectibleTest: " << passCount << " passed, "
		<< failCount << " failed" << std::endl;
	return failCount == 0 ? 0 : 1;
}
