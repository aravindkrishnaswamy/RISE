//  BDPTZeroDensityConnectibleTest.cpp - Pins DL-430: BDPT's MISWeight
//  must give a ZERO ratio, not 1, where a NON-delta, connectible vertex
//  generates a reverse density of exactly zero.
//
//  Author: Aravind Krishnaswamy
//  Date of Birth: 2026-10-03
//  Tabs: 4
//  Comments:
//
//    THE DEFECT.  `BDPTIntegrator::MISWeight` maps every zero `pdfRev`
//    to 1 (remap0) so the ratio chain survives a DELTA vertex, whose
//    density is a Dirac the strategies through it share.  A zero produced
//    by a NON-delta, connectible vertex means something else: that vertex
//    can never scatter toward its neighbour, so every strategy that needs
//    it to has density zero.  Remapped to 1, those impossible strategies
//    entered the power-heuristic denominator with ratio 1/pdfFwd and
//    deflated the weight of the strategies that DO generate the path.
//
//    THE FIXTURE.  A 2x2 floor lit by a 4x4 one-sided area emitter
//    behind the camera; nothing else, so every path has exactly one floor
//    vertex and PT is exact.  The floor's material is replaced, after the
//    scene loads, by one of two test-local materials whose BSDF is the
//    ordinary 0.5 Lambertian:
//      null SPF  -- `GetSPF()` returns null (`datadriven_material`'s state
//                   before DL-325): the BSDF is evaluable for connections
//                   but the vertex can never be generated by scattering.
//      half SPF  -- the Lambertian SPF restricted to world x >= 0: it emits
//                   only there and its `Pdf` reports 0 for x < 0 (a
//                   consistent sub-density), so floor points with x > 0 see
//                   the emitter through a hole in their sampling density.
//    Both have the SAME expected image as plain `lambertian_material`
//    under PT (NEE carries the hole at MIS weight 1), so the reference is
//    PT on the plain Lambertian floor, and each half of the image is
//    compared separately (the half-SPF hole covers one half only).
//
//    RED-PROOF: see docs/DEBT_LEDGER.md DL-430 for the measured numbers.
//
