template<class T>
class Owned
{
public:
	explicit Owned( T* q = 0 ) : p( q ) {}
	~Owned() { if( p ) p->release(); }
	T*   operator->() const { return p; }
	T&   operator*()  const { return *p; }
	T*   get()        const { return p; }
	explicit operator bool() const { return p != 0; }
private:
	T* p;
	Owned( const Owned& );
	Owned& operator=( const Owned& );
};

//////////////////////////////////////////////////////////////////////
// An INDEPENDENT writer of the .hair format (see the file header for
// why it does not share a line with the reader).  Little-endian packing
// is done byte by byte so the writer is correct on any host, exactly as
// the reader's decode is.
//////////////////////////////////////////////////////////////////////

void PutU32( std::vector<unsigned char>& b, const unsigned int v )
{
	b.push_back( (unsigned char)( v         & 0xFF ) );
	b.push_back( (unsigned char)( ( v >>  8 ) & 0xFF ) );
	b.push_back( (unsigned char)( ( v >> 16 ) & 0xFF ) );
	b.push_back( (unsigned char)( ( v >> 24 ) & 0xFF ) );
}

void PutU16( std::vector<unsigned char>& b, const unsigned int v )
{
	b.push_back( (unsigned char)( v        & 0xFF ) );
	b.push_back( (unsigned char)( ( v >> 8 ) & 0xFF ) );
}

void PutF32( std::vector<unsigned char>& b, const float f )
{
	unsigned int bits = 0;
	memcpy( &bits, &f, sizeof(bits) );
	PutU32( b, bits );
}

//! One strand as this test wants to reason about it.
struct TestStrand
{
	std::vector<float> pts;			//!< x y z triples
	std::vector<float> thickness;	//!< one per point
};

//! Everything the writer can be told to do, INCLUDING the malformed
//! things -- the negative fixtures are the reason the header counts and
//! the flags are separately overridable from the strand list.
struct HairFileSpec
{
	std::vector<TestStrand> strands;

	bool writeSegments;
	bool writeThickness;
	bool writeTransparency;
	bool writeColors;

	unsigned int defaultSegments;
	float        defaultThickness;

	// Malformation knobs.  -1 / 0 = "derive it honestly from `strands`".
	long long    forceStrandCount;	//!< override the header's strand count
	long long    forcePointCount;	//!< override the header's point count
	unsigned int extraFlagBits;		//!< OR'd into the flags word
	bool         clearPointsFlag;
	bool         badMagic;
	unsigned int truncateBytes;		//!< drop this many bytes off the end
	unsigned int trailingBytes;		//!< append this many junk bytes
	long long    forceSegmentOfStrand0;	//!< override strand 0's segments-array entry

	HairFileSpec() :
		writeSegments( true ), writeThickness( true ),
		writeTransparency( false ), writeColors( false ),
		defaultSegments( 0 ), defaultThickness( 0.02f ),
		forceStrandCount( -1 ), forcePointCount( -1 ), extraFlagBits( 0 ),
		clearPointsFlag( false ), badMagic( false ),
		truncateBytes( 0 ), trailingBytes( 0 ), forceSegmentOfStrand0( -1 )
	{
	}
};

std::string TempDir()
{
	const char* tmp = getenv( "TMPDIR" );
	std::string dir = tmp ? tmp : "/tmp/";
	if( !dir.empty() && dir[dir.size()-1] != '/' ) dir += "/";
	return dir;
}

//! Writes `spec` to a temp file and returns its path.
std::string MakeHairFile( const std::string& tag, const HairFileSpec& spec )
{
	unsigned int numPoints = 0;
	for( size_t i = 0; i < spec.strands.size(); ++i ) {
		numPoints += (unsigned int)( spec.strands[i].pts.size() / 3 );
	}

	const unsigned int hdrStrands = ( spec.forceStrandCount >= 0 )
		? (unsigned int)spec.forceStrandCount : (unsigned int)spec.strands.size();
	const unsigned int hdrPoints  = ( spec.forcePointCount >= 0 )
		? (unsigned int)spec.forcePointCount : numPoints;

	unsigned int flags = spec.clearPointsFlag ? 0u : ( 1u << 1 );
	if( spec.writeSegments )     flags |= ( 1u << 0 );
	if( spec.writeThickness )    flags |= ( 1u << 2 );
	if( spec.writeTransparency ) flags |= ( 1u << 3 );
	if( spec.writeColors )       flags |= ( 1u << 4 );
	flags |= spec.extraFlagBits;

	std::vector<unsigned char> b;
	if( spec.badMagic ) {
		b.push_back( 'H' ); b.push_back( 'A' ); b.push_back( 'I' ); b.push_back( 'X' );
	} else {
		b.push_back( 'H' ); b.push_back( 'A' ); b.push_back( 'I' ); b.push_back( 'R' );
	}
	PutU32( b, hdrStrands );
	PutU32( b, hdrPoints );
	PutU32( b, flags );
	PutU32( b, spec.defaultSegments );
	PutF32( b, spec.defaultThickness );
	PutF32( b, 0.0f );							// default transparency
	PutF32( b, 1.0f ); PutF32( b, 1.0f ); PutF32( b, 1.0f );	// default colour
	{
		const char* info = "RISE HairFileImportTest fixture";
		for( unsigned int i = 0; i < 88; ++i ) {
			b.push_back( (unsigned char)( i < strlen( info ) ? info[i] : 0 ) );
		}
	}

	if( spec.writeSegments ) {
		for( size_t i = 0; i < spec.strands.size(); ++i ) {
			unsigned int segs = (unsigned int)( spec.strands[i].pts.size() / 3 ) - 1u;
			if( i == 0 && spec.forceSegmentOfStrand0 >= 0 ) {
				segs = (unsigned int)spec.forceSegmentOfStrand0;
			}
			PutU16( b, segs );
		}
	}
	for( size_t i = 0; i < spec.strands.size(); ++i ) {
		for( size_t k = 0; k < spec.strands[i].pts.size(); ++k ) { PutF32( b, spec.strands[i].pts[k] ); }
	}
	if( spec.writeThickness ) {
		for( size_t i = 0; i < spec.strands.size(); ++i ) {
			for( size_t k = 0; k < spec.strands[i].thickness.size(); ++k ) { PutF32( b, spec.strands[i].thickness[k] ); }
		}
	}
	if( spec.writeTransparency ) {
		for( unsigned int i = 0; i < numPoints; ++i ) { PutF32( b, 0.0f ); }
	}
	if( spec.writeColors ) {
		for( unsigned int i = 0; i < numPoints; ++i ) { PutF32( b, 0.5f ); PutF32( b, 0.5f ); PutF32( b, 0.5f ); }
	}

	for( unsigned int i = 0; i < spec.trailingBytes; ++i ) { b.push_back( 0xAB ); }
	if( spec.truncateBytes > 0 ) {
		const size_t keep = ( spec.truncateBytes < b.size() ) ? b.size() - spec.truncateBytes : 0;
		b.resize( keep );
	}

	char pid[32];
	std::snprintf( pid, sizeof(pid), "%d", (int)::getpid() );
	const std::string path = TempDir() + "rise_hairfile_" + tag + "_" + pid + ".hair";
	std::ofstream f( path.c_str(), std::ios::binary | std::ios::trunc );
	if( !b.empty() ) { f.write( (const char*)&b[0], (std::streamsize)b.size() ); }
	f.close();
	return path;
}

//! The canonical positive fixture: five upright strands with 4, 3, 5, 2
//! and 6 points respectively -- deliberately RAGGED, because a uniform
//! strand length is exactly the shape in which an off-by-one in the
//! per-strand cursor stays invisible.
std::vector<TestStrand> CanonicalStrands()
{
	const unsigned int counts[5] = { 4, 3, 5, 2, 6 };
	std::vector<TestStrand> out;
	for( unsigned int s = 0; s < 5; ++s ) {
		TestStrand ts;
		for( unsigned int k = 0; k < counts[s]; ++k ) {
			const float t = (float)k / (float)( counts[s] - 1 );
			ts.pts.push_back( 0.25f * (float)s + 0.1f * t * t );	// x: leans with height
			ts.pts.push_back( 0.5f * t );							// y: grows up
			ts.pts.push_back( -0.125f * (float)s );					// z
			ts.thickness.push_back( 0.02f - 0.012f * t );			// 0.02 -> 0.008
		}
		out.push_back( ts );
	}
	return out;
}

bool NearF( const double a, const double b, const double tol = 1e-6 )
{
	return std::fabs( a - b ) <= tol;
}

