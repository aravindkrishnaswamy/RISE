//////////////////////////////////////////////////////////////////////
//
//  HairFileImportTest.cpp - Contract test for the Cem Yuksel `.hair`
//    IMPORTER: `HairFileLoader` and `hair_geometry`'s `file` mode
//    (Phase 2 slice P2-B of the hair/fur arc, docs/HAIR_FUR_DESIGN.md
//    section 7).
//
//  WHAT THIS TEST OWNS, and why it is its own file.  HairGeneratorTest
//  owns the GROW mode (recipe -> strands) and HairGuidesTest owns the
//  guide-interpolation delta on top of it.  Neither has anything to say
//  about a groom that arrives as bytes on disk, which is a different
//  risk surface entirely: a binary parser's failure modes are
//  truncation, a lying header, and silently-misread arrays, not
//  placement arithmetic.
//
//  THE FIXTURES ARE WRITTEN BY THIS TEST, and that is the point.
//  `MakeHairFile` below is an INDEPENDENT writer of the published
//  format -- it packs the 128-byte header and the arrays from the
//  specification table, with no code shared with the reader under test
//  -- so every positional assertion is a genuine writer/reader
//  round-trip rather than a reader agreeing with itself.  It is also
//  the only way to author the NEGATIVE fixtures at all: a truncated
//  file, a bad magic, a header whose segment counts contradict its
//  point count, a reserved flag bit.  Those cannot be committed assets;
//  a corrupt file in the scene corpus would be a liability, and a scene
//  referencing a file that does not exist cannot go in the corpus
//  either.
//
//  ONE fixture IS committed -- scenes/Tests/ChunkCoverage/assets/
//  tiny.hair, 392 bytes, generated by that directory's
//  gen_chunkcoverage_assets.py alongside the .3ds / .exr / .tiff / .bdf
//  it already generates -- because the ChunkCoverage scene for `file`
//  mode needs a real asset on disk.  Group 7 loads that exact file, so
//  the corpus scene cannot rot silently.
//
//  The seven groups:
//
//    1. ROUND TRIP, ALL ARRAYS PRESENT.  A 5-strand file with an
//       explicit segments array and a per-point thickness array: every
//       header field, every per-strand point count, every control point
//       and every thickness comes back exactly as written.
//
//    2. THE HEADER-DEFAULT PATHS.  The same groom with the segments
//       array absent (uniform default segment count), with the
//       thickness array absent (header default width), and with both
//       absent.
//
//    3. REFUSALS.  Fourteen malformed files, each of which must be
//       refused WITHOUT reading past the end of anything: bad magic, a
//       stub shorter than the header, a truncated array section, no
//       points flag, a reserved flag bit, zero counts, over-cap counts,
//       a segments array that does not sum to the point count, a zero
//       segment entry, a default-segments arithmetic mismatch, a
//       non-finite header thickness.  Plus the one malformation that is
//       NOT fatal: trailing bytes after the arrays, which load with a
//       warning.
//
//    4. STRAND CONSTRUCTION.  Widths come from each strand's FIRST and
//       LAST thickness (interior values are dropped, by design); the
//       two width parameters MULTIPLY rather than replace; a strand
//       with a non-finite control point or an unusable width is dropped
//       and counted while its neighbours survive; an all-bad file
//       fails; a file with no width at all falls back to RISE's
//       human-hair defaults, which the multipliers then scale.
//
//    5. THE GEOMETRY.  The strands reach `HairGeometry` intact --
//       control points, root/tip widths and the (0,0) root UV all
//       checked against the arrays this test wrote -- and the imported
//       groom is in explicit-strand mode (already realized).
//
//    6. THE CHUNK.  `hair_geometry { file ... }` parses end-to-end and
//       registers a groom of the right size; `file` + `base_geometry`,
//       `file` + `guides`, `file` + any other grow-mode parameter, and
//       a chunk with NEITHER source are each refused with a diagnostic
//       naming what was wrong; so are a missing file and a
//       non-positive width multiplier.
//
//    7. THE COMMITTED CORPUS ASSET.  tiny.hair loads and matches what
//       its generator says it contains.
//
//////////////////////////////////////////////////////////////////////

