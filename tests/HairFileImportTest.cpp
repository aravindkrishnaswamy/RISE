static void RunCorpusAsset()
{
	std::cout << "=== 7. The committed ChunkCoverage asset ===" << std::endl;

	// Relative to the repo root, which is where the suite runs -- the
	// same path the scene file names.  The media-path locator resolves
	// it against $RISE_MEDIA_PATH otherwise.
	const char* kAsset = "scenes/Tests/ChunkCoverage/assets/tiny.hair";

	HairFileData d;
	const bool ok = LoadHairFile( kAsset, d, "corpus" );
	Check( ok, "the committed tiny.hair loads (guards cc_hair_file_geometry.RISEscene against asset rot)" );
	if( !ok ) return;

	Check( d.numStrands == 4 && d.numPoints == 16,
	       "tiny.hair is the 4-strand / 16-point groom its generator documents" );
	Check( d.hasSegmentsArray && d.hasThicknessArray,
	       "tiny.hair exercises the optional-array-PRESENT path (which the header-default fixtures do not)" );

	std::vector<HairGeometry::StrandDesc> strands;
	Check( BuildStrandsFromHairFile( d, 1.0, 1.0, strands, "corpus" ) && strands.size() == 4,
	       "every strand of tiny.hair converts" );
	if( strands.size() == 4 ) {
		Check( NearF( strands[0].rootWidth, 0.02, 1e-7 ) && NearF( strands[0].tipWidth, 0.008, 1e-7 ),
		       "tiny.hair's documented 0.02 -> 0.008 taper is what comes out" );
	}
}

