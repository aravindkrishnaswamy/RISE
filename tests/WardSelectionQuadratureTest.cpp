static Input MakeInput(int family,double theta,double azimuth,double tilt) {
    const double ax[7][3]={{.1,0,0},{.3,0,0},{.6,0,0},{.3,0,0},{.6,0,0},{.2,0,0},{.1,.3,.6}};
    const double ay[7][3]={{.1,0,0},{.3,0,0},{.6,0,0},{.12,0,0},{.12,0,0},{.5,0,0},{.3,.12,.6}};
    Input in={};theta*=pi/180;azimuth*=pi/180;tilt*=pi/180;
    in.vx=std::sin(theta)*std::cos(azimuth);in.vy=std::sin(theta)*std::sin(azimuth);in.nv=std::cos(theta);
    in.gx=std::sin(tilt);in.ng=std::cos(tilt);in.wD=.4;in.count=family==6?3:1;
    const double weights[3]={.2,.5,.8};
    for(int j=0;j<in.count;++j){in.ax[j]=ax[family][j];in.ay[j]=ay[family][j];in.weight[j]=family==6?weights[j]:.5;}
    return in;
}
