//
//  SobolSequence.h - Owen-scrambled Sobol' sequence.
//
//  Two draw shapes:
//  - Sample()     (Get1D): true per-dimension Sobol' sequence from
//                 Joe-Kuo `new-joe-kuo-6.21201` (D(6)) initial direction
//                 numbers (SobolDirectionNumbers.cpp, license/provenance
//                 there), Owen-scrambled per dimension. Never reduced
//                 modulo 2 (same-parity Owen draws without index
//                 permutation lock their leading digit). Dimensions >=
//                 kNumDimensions wrap with an Owen-permuted sample index.
//  - SamplePair() (Get2D): padded (0,2)-net from Sobol' dims 0 & 1 at an
//                 Owen-permuted sample index (`ScrambleIndex`), preserving
//                 every dyadic (0,M,2)-net prefix without knowing spp.
//                 Group 0 stays unpermuted for ZSobolSampler's Morton
//                 blue noise.
//
//  Counting floors (mathematical limits, not defects): among 200+ active
//  dimensions, pigeonhole collisions in leading generator rows are
//  unavoidable below 2^M samples; similarly, `ScrambleIndex` group pairs
//  meet the Boolean-function counting floor below 64 spp (0% at >= 64 spp).
//
//  References:
//    - Sobol', "On the distribution of points in a cube and the
//      approximate evaluation of integrals", USSR Comp. Math. 1967
//    - Bratley and Fox, "ALGORITHM 659: Implementing Sobol's
//      quasirandom sequence generator", ACM TOMS 1988
//    - Joe and Kuo, "Constructing Sobol sequences with better
//      two-dimensional projections", SIAM J. Sci. Comput. 2008
//    - Burley, "Practical Hash-based Owen Scrambling", JCGT 2020
//    - Owen, "Randomly Permuted (t,m,s)-Nets and (t,s)-Sequences",
//      Monte Carlo and Quasi-Monte Carlo Methods, 1995
//    - Pharr, Jakob, Humphreys, "Physically Based Rendering" (4e),
//      Chapter 8: Sampling and Reconstruction
//
