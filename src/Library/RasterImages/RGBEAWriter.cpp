#include "pch.h"
#include <stdio.h>					// for sprintf
#include <string.h>					// for strlen and strncmp
#include "RGBEAWriter.h"
#include <limits>
#include <new>
#include "../Interfaces/ILog.h"
#include "../Version.h"

using namespace RISE;
using namespace RISE::Implementation;

RGBEAWriter::RGBEAWriter( IWriteBuffer& buffer ) :
  pWriteBuffer( buffer ),
  pBuffer( 0 )
{
	pWriteBuffer.addref();
}

RGBEAWriter::~RGBEAWriter( )
{
	pWriteBuffer.release();

	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = 0;
	}
}

void RGBEAWriter::BeginWrite( const unsigned int width, const unsigned int height )
{
	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
	}
	if( width == 0 || height == 0 || width > (std::numeric_limits<unsigned int>::max() - 2048U) / 8 / height ||
		width > std::numeric_limits<size_t>::max() / 8 / height ) {
		GlobalLog()->PrintEasyError( "RGBEAWriter: Invalid image dimensions" );
		return;
	}
	const size_t bytes = static_cast<size_t>(width) * height * 8;
	pBuffer = new (std::nothrow) unsigned char[bytes];
	if( !pBuffer ) {
		GlobalLog()->PrintEasyError( "RGBEAWriter: Could not allocate pixel buffer" );
		return;
	}
	bufW = width;
	bufH = height;
	GlobalLog()->PrintNew( pBuffer, __FILE__, __LINE__, "buffer" );

	// Build the header
	char szHeader[2048] = {0};
	{
		static const char * szSignature = "#?RGBEA\n";
		static const int MAX_BUFFER_SIZE = 256;
		char szWhoWroteIt[MAX_BUFFER_SIZE] = {0};
		snprintf( szWhoWroteIt, MAX_BUFFER_SIZE, "# Generated by R.I.S.E. v%d.%d.%d build %d\n", RISE_VER_MAJOR_VERSION, RISE_VER_MINOR_VERSION, RISE_VER_REVISION_VERSION, RISE_VER_BUILD_VERSION );
		static const char * szImageType = "FORMAT=64-bit_rle_rgbea\n\n";
		char szImageDimensions[MAX_BUFFER_SIZE] = {0};
		snprintf( szImageDimensions, MAX_BUFFER_SIZE, "-Y %u +X %u\n", height, width );

		strcpy( szHeader, szSignature );
		strcat( szHeader, szWhoWroteIt );
		strcat( szHeader, szImageType );
		strcat( szHeader, szImageDimensions );
	}	

	// Write the header
	// Make sure there's enough room in the buffer first
	pWriteBuffer.Resize( static_cast<unsigned int>(bytes + strlen(szHeader)) );

	// Write out the header
	if( !pWriteBuffer.setBytes( szHeader, static_cast<unsigned int>(strlen(szHeader)) ) ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
	}

}

void RGBEAWriter::WriteColor( const RISEColor& c, const unsigned int x, const unsigned int y )
{
	const unsigned char RGBEBase = 128;

	if( pBuffer && x < bufW && y < bufH ) {
		// Unlike the RGBE and HDR formats, our RGBEA format is in the ROMM RGB color space
		ROMMRGBPel p = c.base;
		Scalar v = ColorMath::MaxValue(p);
		int e;

		const size_t idx = (static_cast<size_t>(y)*bufW+x)*8;

		if( v < 1e-32 ) {
			//R
			pBuffer[idx] = 0;
			pBuffer[idx+1] = 0;
			//G
			pBuffer[idx+2] = 0;
			pBuffer[idx+3] = 0;
			//B
			pBuffer[idx+4] = 0;
			pBuffer[idx+5] = 0;
			//E
			pBuffer[idx+6] = 0;
			//A
			pBuffer[idx+7] = 0;
		} else {
			v = frexp(v,&e) * 65536.0/v;
			// RISE RGBEA stores its mantissas least significant byte first.
			const unsigned short samples[] = {
				static_cast<unsigned short>(p.r*v),
				static_cast<unsigned short>(p.g*v),
				static_cast<unsigned short>(p.b*v)
			};
			for( unsigned int i = 0; i < 3; ++i ) {
				pBuffer[idx + i*2] = static_cast<unsigned char>(samples[i]);
				pBuffer[idx + i*2 + 1] = static_cast<unsigned char>(samples[i] >> 8);
			}
			pBuffer[idx+6] = (e + RGBEBase);
			pBuffer[idx+7] = (unsigned char)(c.a*255.0);
		}
	}
}

void RGBEAWriter::EndWrite( )
{
	if( pBuffer ) pWriteBuffer.setBytes( pBuffer, bufW*bufH*8 );
}
