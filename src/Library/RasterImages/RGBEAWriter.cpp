#include "pch.h"
#include <stdio.h>					// for sprintf
#include <string>
#include "RGBEAWriter.h"
#include <limits>
#include <memory>
#include <stdexcept>
#include "../Interfaces/ILog.h"
#include "../Version.h"
#include "../Utilities/Color/ColorUtils.h"

using namespace RISE;
using namespace RISE::Implementation;

RGBEAWriter::RGBEAWriter( IWriteBuffer& buffer ) :
  pWriteBuffer( buffer ),
  pBuffer( 0 ),
  bufW( 0 ),
  bufH( 0 )
{
	pWriteBuffer.addref();
}

RGBEAWriter::~RGBEAWriter( )
{
	pWriteBuffer.release();

	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = 0;
	}
}

void RGBEAWriter::BeginWrite( const unsigned int width, const unsigned int height )
{
	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
	}
	bufW = bufH = 0;
	if( !width || !height ) throw std::invalid_argument("RGBEAWriter: Dimensions must be nonzero");
	const std::string header = "#?RGBEA\n# Generated by R.I.S.E. v" +
		std::to_string(RISE_VER_MAJOR_VERSION) + "." + std::to_string(RISE_VER_MINOR_VERSION) + "." +
		std::to_string(RISE_VER_REVISION_VERSION) + " build " + std::to_string(RISE_VER_BUILD_VERSION) +
		"\nFORMAT=64-bit_rle_rgbea\n\n-Y " + std::to_string(height) + " +X " + std::to_string(width) + "\n";
	if( header.size() > std::numeric_limits<unsigned int>::max() ||
		width > (std::numeric_limits<unsigned int>::max() - header.size()) / 8 / height ||
		width > (std::numeric_limits<size_t>::max() - header.size()) / 8 / height )
		throw std::length_error("RGBEAWriter: Image exceeds the output buffer size limit");
	const auto bytes = static_cast<size_t>(width) * height * 8;
	// Keep the new image inactive until allocation and header output succeed.
	auto pixels = std::make_unique<unsigned char[]>(bytes);
	// Resize is advisory; a borrowed sink can already have enough capacity.
	pWriteBuffer.Resize( static_cast<unsigned int>(bytes + header.size()) );
	if( !pWriteBuffer.setBytes( header.data(), static_cast<unsigned int>(header.size()) ) )
		throw std::runtime_error("RGBEAWriter: Failed to write image header");
	bufW = width;
	bufH = height;
	pBuffer = pixels.release();
	GlobalLog()->PrintNew( pBuffer, __FILE__, __LINE__, "RGBEA pixels" );
}

void RGBEAWriter::WriteColor( const RISEColor& c, const unsigned int x, const unsigned int y )
{
	if( pBuffer && x < bufW && y < bufH ) {
		// Unlike the RGBE and HDR formats, our RGBEA format is in the ROMM RGB color space
		ROMMRGBPel p = c.base;
		unsigned int samples[3];unsigned char exponent;
		ColorUtils::PackSharedExponentRGB<16>(p,samples,exponent);

		const size_t idx = (static_cast<size_t>(y)*bufW+x)*8;

		// RISE RGBEA stores its mantissas least significant byte first.
		for( unsigned int i = 0; i < 3; ++i ) {
			pBuffer[idx + i*2] = static_cast<unsigned char>(samples[i]);
			pBuffer[idx + i*2 + 1] = static_cast<unsigned char>(samples[i] >> 8);
		}
		pBuffer[idx+6] = exponent;
		pBuffer[idx+7] = c.IntegerizeAlpha<unsigned char>(255.0);
	}
}

void RGBEAWriter::EndWrite( )
{
	if( !pBuffer ) return;
	const auto bytes = static_cast<size_t>(bufW) * bufH * 8;
	try {
		if( !pWriteBuffer.setBytes( pBuffer, static_cast<unsigned int>(bytes) ) )
			throw std::runtime_error("RGBEAWriter: Failed to write image pixels");
	} catch( ... ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
		bufW = bufH = 0;
		throw;
	}
}
