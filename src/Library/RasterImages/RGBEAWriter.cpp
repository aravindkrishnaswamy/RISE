using namespace RISE;
using namespace RISE::Implementation;

RGBEAWriter::RGBEAWriter( IWriteBuffer& buffer ) :
  pWriteBuffer( buffer ),
  pBuffer( 0 )
{
	pWriteBuffer.addref();
}

RGBEAWriter::~RGBEAWriter( )
{
	pWriteBuffer.release();

	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = 0;
	}
}

void RGBEAWriter::BeginWrite( const unsigned int width, const unsigned int height )
{
	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
	}
	if( width == 0 || height == 0 || width > (std::numeric_limits<unsigned int>::max() - 2048U) / 8 / height ||
		width > std::numeric_limits<size_t>::max() / 8 / height ) {
		GlobalLog()->PrintEasyError( "RGBEAWriter: Invalid image dimensions" );
		return;
	}
	const size_t bytes = static_cast<size_t>(width) * height * 8;
	pBuffer = new (std::nothrow) unsigned char[bytes];
	if( !pBuffer ) {
		GlobalLog()->PrintEasyError( "RGBEAWriter: Could not allocate pixel buffer" );
		return;
	}
	bufW = width;
	bufH = height;
	GlobalLog()->PrintNew( pBuffer, __FILE__, __LINE__, "buffer" );

	const std::string header = "#?RGBEA\n# Generated by R.I.S.E. v" +
		std::to_string(RISE_VER_MAJOR_VERSION) + "." + std::to_string(RISE_VER_MINOR_VERSION) + "." +
		std::to_string(RISE_VER_REVISION_VERSION) + " build " + std::to_string(RISE_VER_BUILD_VERSION) +
		"\nFORMAT=64-bit_rle_rgbea\n\n-Y " + std::to_string(height) + " +X " + std::to_string(width) + "\n";

	// Write the header
	// Make sure there's enough room in the buffer first
	pWriteBuffer.Resize( static_cast<unsigned int>(bytes + header.size()) );

	// Write out the header
	if( !pWriteBuffer.setBytes( header.data(), static_cast<unsigned int>(header.size()) ) ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
	}

}

void RGBEAWriter::WriteColor( const RISEColor& c, const unsigned int x, const unsigned int y )
{
	if( pBuffer && x < bufW && y < bufH ) {
		// Unlike the RGBE and HDR formats, our RGBEA format is in the ROMM RGB color space
		ROMMRGBPel p = c.base;
		unsigned int samples[3];unsigned char exponent;
		ColorUtils::PackSharedExponentRGB<16>(p,samples,exponent);

		const size_t idx = (static_cast<size_t>(y)*bufW+x)*8;

		// RISE RGBEA stores its mantissas least significant byte first.
		for( unsigned int i = 0; i < 3; ++i ) {
			pBuffer[idx + i*2] = static_cast<unsigned char>(samples[i]);
			pBuffer[idx + i*2 + 1] = static_cast<unsigned char>(samples[i] >> 8);
		}
		pBuffer[idx+6] = exponent;
		pBuffer[idx+7] = c.IntegerizeAlpha<unsigned char>(255.0);
	}
}

void RGBEAWriter::EndWrite( )
{
	if( pBuffer ) pWriteBuffer.setBytes( pBuffer, bufW*bufH*8 );
}
