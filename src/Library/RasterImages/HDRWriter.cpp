#include "pch.h"
#include <limits>
#include <memory>
#include <stdexcept>
#include <string>
#include "HDRWriter.h"
#include "../Interfaces/ILog.h"
#include "../Version.h"

using namespace RISE;
using namespace RISE::Implementation;

HDRWriter::HDRWriter( IWriteBuffer& buffer, const COLOR_SPACE color_space_ ) :
  pWriteBuffer( buffer ),
  pBuffer( 0 ),
  bufW( 0 ),
  bufH( 0 ),
  color_space( color_space_ )
{
	pWriteBuffer.addref();
}

HDRWriter::~HDRWriter( )
{
	pWriteBuffer.release();

	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = 0;
	}
}

void HDRWriter::BeginWrite( const unsigned int width, const unsigned int height )
{
	if( pBuffer ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
	}
	bufW = bufH = 0;
	if( !width || !height ) throw std::invalid_argument("HDRWriter: Dimensions must be nonzero");
	const std::string header = "#?RADIANCE\n# Generated by R.I.S.E. v" +
		std::to_string(RISE_VER_MAJOR_VERSION) + "." + std::to_string(RISE_VER_MINOR_VERSION) + "." +
		std::to_string(RISE_VER_REVISION_VERSION) + " build " + std::to_string(RISE_VER_BUILD_VERSION) +
		"\nFORMAT=32-bit_rle_rgbe\n\n-Y " + std::to_string(height) + " +X " + std::to_string(width) + "\n";
	if( header.size() > std::numeric_limits<unsigned int>::max() ||
		width > (std::numeric_limits<unsigned int>::max() - header.size()) / 4 / height ||
		width > (std::numeric_limits<size_t>::max() - header.size()) / 4 / height )
		throw std::length_error("HDRWriter: Image exceeds the output buffer size limit");
	const auto bytes = static_cast<size_t>(width) * height * 4;
	// Keep the new image inactive until allocation and header output succeed.
	auto pixels = std::make_unique<unsigned char[]>(bytes);
	// Resize is advisory; a borrowed sink can already have enough capacity.
	pWriteBuffer.Resize( static_cast<unsigned int>(bytes + header.size()) );
	if( !pWriteBuffer.setBytes( header.data(), static_cast<unsigned int>(header.size()) ) )
		throw std::runtime_error("HDRWriter: Failed to write image header");
	bufW = width;
	bufH = height;
	pBuffer = pixels.release();
	GlobalLog()->PrintNew( pBuffer, __FILE__, __LINE__, "HDR pixels" );
}

void HDRWriter::WriteColor( const RISEColor& c, const unsigned int x, const unsigned int y )
{
	if( pBuffer && x < bufW && y < bufH ) {
		// No alpha in RGBE, so composite against black

		switch( color_space )
		{
		case eColorSpace_Rec709RGB_Linear:
			{
				Rec709RGBPel p = Rec709RGBPel(c.base) * c.a;
				WriteHDRPixelToBuffer( x, y, p );
			} break;
		case eColorSpace_sRGB:
			{
				sRGBPel p = sRGBPel(c.base) * c.a;
				WriteHDRPixelToBuffer( x, y, p );
			} break;
		case eColorSpace_ROMMRGB_Linear:
			{
				ROMMRGBPel p = ROMMRGBPel(c.base) * c.a;
				WriteHDRPixelToBuffer( x, y, p );
			} break;
		case eColorSpace_ProPhotoRGB:
			{
				ProPhotoRGBPel p = ProPhotoRGBPel(c.base) * c.a;
				WriteHDRPixelToBuffer( x, y, p );
			} break;
		}
	}
}

void HDRWriter::EndWrite( )
{
	if( !pBuffer ) return;
	const auto bytes = static_cast<size_t>(bufW) * bufH * 4;
	try {
		if( !pWriteBuffer.setBytes( pBuffer, static_cast<unsigned int>(bytes) ) )
			throw std::runtime_error("HDRWriter: Failed to write image pixels");
	} catch( ... ) {
		GlobalLog()->PrintDelete( pBuffer, __FILE__, __LINE__ );
		delete [] pBuffer;
		pBuffer = nullptr;
		bufW = bufH = 0;
		throw;
	}
}
